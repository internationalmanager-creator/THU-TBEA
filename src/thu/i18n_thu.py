def get(lang="es"):
    """Devuelve el dict de traducciones + domain_names."""
    base = _T.get(lang, _T["es"]).copy()
    base["domain_names"] = _domain_names(lang)
    return base


def available():
    return list(_T.keys())


def lang_label(code):
    return {"es": "Espanol", "en": "English", "de": "Deutsch"}.get(code, code)


